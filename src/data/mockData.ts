export const BN_DIGITS: Record<string, string> = {
  '0': '০',
  '1': '১',
  '2': '২',
  '3': '৩',
  '4': '৪',
  '5': '৫',
  '6': '৬',
  '7': '৭',
  '8': '৮',
  '9': '৯',
};

export function toBnNum(num: number | string): string {
  const str = typeof num === 'number' ? num.toLocaleString('en-US') : num.toString();
  return str.replace(/\d/g, (d) => BN_DIGITS[d] || d);
}

export function formatPriceBn(amount: number): string {
  return `৳${toBnNum(amount)}`;
}

